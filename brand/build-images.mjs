// Builds the served brand imagery from brand/curation.json.
//
//   node brand/build-images.mjs
//
// For every kept photo: renames the original in public/brand to its curated
// name, writes an optimised JPEG to public/images/brand/<name>.jpg (the
// fallback; next/image serves AVIF/WebP at responsive sizes on top), and
// records dimensions + a tiny blur placeholder in
// src/lib/brand-images.generated.ts. Rejected originals move to _rejected/
// (outside public, git-ignored). Old served names are mapped to new ones in
// brand/legacy-map.json so existing database rows keep resolving.
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";

const require = createRequire(import.meta.url);
const sharp = require("sharp");
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const manifestPath = path.join(root, "brand/curation.json");
const entries = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const originals = path.join(root, "public/brand");
const served = path.join(root, "public/images/brand");
const rejected = path.join(root, "_rejected");
fs.mkdirSync(rejected, { recursive: true });

// Only names that were actually served before need a legacy mapping.
const legacyFile = path.join(root, "brand/legacy-map.json");
const previousLegacy = fs.existsSync(legacyFile) ? JSON.parse(fs.readFileSync(legacyFile, "utf8")) : {};
const previouslyServed = new Set([...Object.keys(previousLegacy), ...fs.readdirSync(served).map((f) => `/images/brand/${f}`)]);
const legacy = { ...previousLegacy };
const images = {};

for (const e of entries) {
  // Locate the original under its old or already-renamed name.
  const ext = path.extname(e.src);
  const renamed = e.name ? `${e.name}${ext.toLowerCase()}` : null;
  let file = [e.src, renamed, e.file].filter(Boolean).map((f) => path.join(originals, f)).find((p) => fs.existsSync(p));
  if (!e.name) {
    if (file) fs.renameSync(file, path.join(rejected, e.src));
    const oldServed = path.join(served, e.src.replace(/\.(png|jpe?g)$/i, "").toLowerCase() + ".jpg");
    if (fs.existsSync(oldServed)) fs.rmSync(oldServed);
    continue;
  }
  if (!file) throw new Error(`Missing original for ${e.src}`);
  if (path.basename(file) !== renamed) {
    fs.renameSync(file, path.join(originals, renamed));
    file = path.join(originals, renamed);
  }
  e.file = renamed;

  const out = path.join(served, `${e.name}.jpg`);
  const img = sharp(file, { limitInputPixels: false }).rotate();
  const info = await img
    .resize(2000, 2000, { fit: "inside", withoutEnlargement: true })
    .flatten({ background: "#EDE6D8" })
    .jpeg({ quality: 82, mozjpeg: true, progressive: true })
    .toFile(out);
  // Placeholder: the photo's average colours on a 2×3 grid (6 hex values),
  // rendered as a blurred SVG by src/lib/brand-images.ts — ~40 bytes each.
  const { data } = await sharp(file, { limitInputPixels: false }).rotate().resize(2, 3, { fit: "fill" }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  let ph = "";
  for (let i = 0; i < data.length; i += 3) ph += [data[i], data[i + 1], data[i + 2]].map((v) => v.toString(16).padStart(2, "0")).join("");
  images[`/images/brand/${e.name}.jpg`] = { w: info.width, h: info.height, ph };

  // Old served name (from the first optimisation pass) → new name.
  const oldName = e.src.replace(/\.(png|jpe?g)$/i, "").toLowerCase();
  if (oldName !== e.name && previouslyServed.has(`/images/brand/${oldName}.jpg`)) {
    legacy[`/images/brand/${oldName}.jpg`] = `/images/brand/${e.name}.jpg`;
    const oldServed = path.join(served, `${oldName}.jpg`);
    if (fs.existsSync(oldServed)) fs.rmSync(oldServed);
  }
}

// A rejected duplicate that was served before points at the twin we kept, so
// old database rows still show the same photo.
const stem = (src) => src.replace(/\.(png|jpe?g)$/i, "").toLowerCase();
for (const e of entries) {
  const twin = !e.name && e.reason?.match(/duplicate of (\S+)/i)?.[1];
  const kept = twin && entries.find((t) => t.name && stem(t.src) === twin.toLowerCase());
  if (kept) legacy[`/images/brand/${stem(e.src)}.jpg`] = `/images/brand/${kept.name}.jpg`;
}

fs.writeFileSync(manifestPath, JSON.stringify(entries, null, 1));
fs.writeFileSync(path.join(root, "brand/legacy-map.json"), JSON.stringify(legacy, null, 1));
fs.writeFileSync(
  path.join(root, "src/lib/brand-images.generated.ts"),
  `// GENERATED by brand/build-images.mjs — do not edit by hand.\n` +
    `// Dimensions and placeholder colours (2×3 grid, hex) for every served brand photo.\n` +
    `export const BRAND_IMAGES: Record<string, { w: number; h: number; ph: string }> = ${JSON.stringify(images)};\n\n` +
    `/** Served paths from before the curation pass, mapped to their new names. */\n` +
    `export const LEGACY_BRAND_PATHS: Record<string, string> = ${JSON.stringify(legacy)};\n`,
);
const total = fs.readdirSync(served).reduce((s, f) => s + fs.statSync(path.join(served, f)).size, 0);
console.log(`${Object.keys(images).length} served images (${(total / 1048576).toFixed(1)} MB), ${entries.filter((e) => !e.name).length} rejected, ${Object.keys(legacy).length} legacy paths mapped`);
